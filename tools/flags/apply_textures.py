#!/usr/bin/env python3
"""Point coat-of-arms definitions at the flag textures render.py made.

Usage (from the mod root):  python3 -I tools/flags/apply_textures.py [--check]

For every manifest row whose texture gfx/coat_of_arms/textured_emblems/cwp_flag_<coa_key without cwp_>.dds
exists, the definition `<coa_key> = { ... }` in common/coat_of_arms/coat_of_arms/cwp_*.txt
is rewritten to show the whole texture, with the source URL and licence in a comment and the
previous pattern-and-emblem body kept below it as a comment (so removing the texture is one
revert). Rows with no definition yet get one appended to cwp_textured_flags.txt; their
flag_definitions come from the gen_flags.py table. Rerunnable: an already converted block
is left alone. BOM and line endings of each file are kept.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
MANIFEST = HERE / "sources.tsv"
TEX = ROOT / "gfx/coat_of_arms/textured_emblems"
COA = ROOT / "common/coat_of_arms/coat_of_arms"
NEW_FILE = COA / "cwp_textured_flags.txt"
MARK = "# texture from Wikimedia Commons:"


def rows():
    lines = MANIFEST.read_text(encoding="utf-8").splitlines()
    header = lines[0].split("\t")
    return [dict(zip(header, (ln.split("\t") + [""] * len(header))[:len(header)])) for ln in lines[1:] if ln.strip()]


def block(key: str, r: dict, nl: str, old_body: list[str] | None) -> str:
    out = [
        f"{key} = {{\t{MARK} {r['commons_file_page']} ({r['licence']}); {r['flag']}",
        '\tpattern = "pattern_solid.tga"',
        '\tcolor1 = "black"',
        "\ttextured_emblem = {",
        f'\t\ttexture = "cwp_flag_{key.removeprefix('cwp_')}.dds"',
        "\t\tinstance = { position = { 0.5 0.5 } scale = { 1.0 1.0 } }",
        "\t}",
    ]
    if old_body:
        out.append("\t# pattern stand-in used before the texture:")
        out += ["\t#" + ln if ln.strip() else "" for ln in old_body]
    out.append("}")
    return nl.join(out)


def find_block(text: str, key: str):
    m = re.search(rf"(?m)^{re.escape(key)} = \{{", text)
    if not m:
        return None
    depth, i = 0, m.end() - 1
    while i < len(text):
        c = text[i]
        if c == "#":
            i = text.find("\n", i)
            if i < 0:
                break
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return m.start(), i + 1
        i += 1
    raise ValueError(f"unbalanced block {key}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="report only")
    args = ap.parse_args()
    files = {p: p.read_bytes() for p in sorted(COA.glob("cwp_*.txt"))}
    texts = {p: b.decode("utf-8-sig") for p, b in files.items()}
    appended = []
    for r in rows():
        key = r["coa_key"]
        if not (TEX / f"cwp_flag_{key.removeprefix('cwp_')}.dds").exists():
            continue
        where = [(p, find_block(t, key)) for p, t in texts.items() if find_block(t, key)]
        if len(where) > 1:
            sys.exit(f"{key} is defined in {len(where)} files")
        if not where:
            appended.append(r)
            continue
        p, (a, b) = where[0]
        t = texts[p]
        nl = "\r\n" if "\r\n" in t else "\n"
        cur = t[a:b]
        if MARK in cur.splitlines()[0]:
            continue
        body = cur.split(nl)[1:-1]
        texts[p] = t[:a] + block(key, r, nl, body) + t[b:]
        print(f"converted {key} in {p.name}")
    if appended:
        t = texts.get(NEW_FILE, "# Cold War Project: flags drawn from public-domain Wikimedia Commons SVGs (tools/flags).\n"
                                "# Generated by tools/flags/apply_textures.py; source and licence per flag in tools/flags/sources.tsv.\n")
        for r in appended:
            if find_block(t, r["coa_key"]):
                continue
            t = t.rstrip("\n") + "\n\n" + block(r["coa_key"], r, "\n", None) + "\n"
            print(f"added {r['coa_key']} to {NEW_FILE.name}")
        texts[NEW_FILE] = t
    if args.check:
        return 0
    for p, t in texts.items():
        bom = files.get(p, b"\xef\xbb\xbf")[:3] == b"\xef\xbb\xbf"
        data = (b"\xef\xbb\xbf" if bom else b"") + t.encode("utf-8")
        if files.get(p) != data:
            p.write_bytes(data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
