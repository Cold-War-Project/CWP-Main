#!/usr/bin/env python3
"""Rebuild the reference/ folder of this guide from the script docs the game generates.

Usage:
    python build_reference.py [DOCS_DIR] [OUT_DIR]

DOCS_DIR defaults to  ~/Documents/Paradox Interactive/Victoria 3/docs
OUT_DIR  defaults to  ../reference (next to this script)

To refresh the game's docs first: launch Victoria 3 with -debug_mode, open the
console and run `script_docs`. Then re-run this script. Standard library only.
"""
import collections
import datetime
import re
import sys
from pathlib import Path

DOCS = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / "Documents/Paradox Interactive/Victoria 3/docs"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "reference"

ITER_EFFECT_PREFIXES = ("every_", "random_", "ordered_")
NOT_ITERATORS = {"random_list", "random_log_scopes", "any_false"}
REGION_ITER = re.compile(r"^(country|state|state_region|strategic_region|province)_in_(.+)$")


def read(name):
    # The logs are UTF-8 with a few stray junk bytes (a doc-generator bug), hence errors="replace".
    return (DOCS / name).read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n")


def write(name, text):
    (OUT / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {name:36} {len(text):>9,} chars")


def header(title, source, intro=""):
    stamp = datetime.date.today().isoformat()
    out = f"# {title}\n\n> Generated by `tools/build_reference.py` on {stamp} from `{source}` "
    out += "(the game's own `script_docs` output). Do not edit by hand; re-run the tool instead.\n\n"
    if intro:
        out += intro.strip() + "\n\n"
    return out


def parse_md_entries(text):
    """effects.log / triggers.log: '## name' blocks."""
    entries = []
    for block in re.split(r"^## ", text, flags=re.M)[1:]:
        lines = block.split("\n")
        e = dict(name=lines[0].strip(), scopes="", targets="", vtype="", traits="", reads="", desc=[])
        for raw in lines[1:]:
            line = raw.rstrip()
            m = re.match(r"\*\*Supported Scopes\*\*: (.*)", line)
            if m:
                e["scopes"] = m.group(1).strip()
                continue
            m = re.match(r"\*\*Supported Targets\*\*: (.*)", line)
            if m:
                e["targets"] = m.group(1).strip()
                continue
            m = re.match(r"\*\*Value Type\*\*: ?(.*)", line)
            if m:
                e["vtype"] = m.group(1).strip()
                continue
            m = re.match(r"Traits: (.*)", line)
            if m:
                e["traits"] = m.group(1).strip()
                continue
            if re.match(r"Reads (gamestate|nothing).*for all scopes", line):
                continue
            if line.strip():
                e["desc"].append(line)
        entries.append(e)
    return entries


def is_iterator(name):
    if name in NOT_ITERATORS:
        return False
    return name.startswith(ITER_EFFECT_PREFIXES) or name.startswith("any_")


def iter_base(name):
    for p in ITER_EFFECT_PREFIXES + ("any_",):
        if name.startswith(p):
            return name[len(p):]
    return name


def fmt_entry(e, kind):
    out = [f"## {e['name']}"]
    out.append(f"- **Scopes:** {e['scopes'] or 'none'}")
    if e["targets"]:
        out.append(f"- **Target:** {e['targets']}")
    if e["vtype"]:
        out.append(f"- **Takes a key from:** `{e['vtype']}`")
    if kind == "trigger" and e["traits"]:
        t = e["traits"]
        if t.startswith("<"):
            t = "comparison (`<  <=  =  !=  >  >=`)"
        elif t == "yes/no":
            t = "boolean (`= yes` / `= no`)"
        out.append(f"- **Form:** {t}")
    if e["desc"]:
        out.append("")
        out.append("```")
        out.extend(e["desc"])
        out.append("```")
    return "\n".join(out) + "\n"


def build_effects_triggers():
    effects = parse_md_entries(read("effects.log"))
    triggers = parse_md_entries(read("triggers.log"))

    plain_eff = [e for e in effects if not is_iterator(e["name"])]
    plain_trg = [e for e in triggers if not is_iterator(e["name"])]

    intro = """
Every **non-iterator** effect, verbatim from the game. List iterators (`every_*`, `random_*`, `ordered_*`)
are in `iterators.md`. Search this file with `^## <name>$`.

"Scopes: none" means *any* scope (the effect does not care what the current scope is).
The usage text inside the code fences is copied from the game and contains a few typos and
copy-paste slips; known ones are listed in chapter 15 of the guide.
"""
    text = header(f"Effects ({len(plain_eff)})", "effects.log", intro)
    text += "\n".join(fmt_entry(e, "effect") for e in plain_eff)
    write("effects.md", text)

    intro = """
Every **non-iterator** trigger, verbatim from the game. List iterators (`any_*`) are in `iterators.md`.
Search this file with `^## <name>$`.

"Scopes: none" means *any* scope. "Form: comparison" triggers accept any comparison operator, and can also be
read as a number in script values and comparisons (e.g. `value = root.prestige`,
`army_power_projection < root.army_power_projection`); see chapter 06 of the guide.
"""
    text = header(f"Triggers ({len(plain_trg)})", "triggers.log", intro)
    text += "\n".join(fmt_entry(e, "trigger") for e in plain_trg)
    write("triggers.md", text)

    # ---- iterators -------------------------------------------------------
    bases = collections.OrderedDict()
    for e in effects:
        if is_iterator(e["name"]):
            bases.setdefault(iter_base(e["name"]), {})[e["name"].split("_")[0]] = e
    for e in triggers:
        if is_iterator(e["name"]):
            bases.setdefault(iter_base(e["name"]), {})["any"] = e

    regions = collections.OrderedDict()
    normal = []
    for base, forms in bases.items():
        m = REGION_ITER.match(base)
        if m:
            regions.setdefault(m.group(2), set()).add(m.group(1))
            continue
        e = forms.get("every") or next(iter(forms.values()))
        desc = e["desc"][0].strip() if e["desc"] else ""
        desc = re.sub(r"^Iterate through (all )?", "", desc)
        extra = [l.strip() for l in e["desc"][1:] if not re.match(r"^(every|random|ordered|any)_", l.strip())]
        # keep extra syntax lines (e.g. variable map iterators) but not the generic usage line
        extra = [l for l in extra if l and not l.startswith(("limit =", "order_by", "position", "min =", "max =", "check_range_bounds", "<effects>"))]
        normal.append((base, e["scopes"] or "none", e["targets"] or "-", desc, " ".join(extra), sorted(forms)))

    intro = """
List iterators. Each **base name** below exists in four forms:

| Form | Kind | Syntax |
|---|---|---|
| `any_<base>` | trigger | `any_<base> = { <count = num/all> / <percent = fixed_point> <triggers> }` |
| `every_<base>` | effect | `every_<base> = { limit = { <triggers> } <effects> }` |
| `random_<base>` | effect | `random_<base> = { limit = { <triggers> } weight = { mtth } <effects> }` (weight optional) |
| `ordered_<base>` | effect | `ordered_<base> = { limit = { <triggers> } order_by = script_value position = int min = int max = script_value check_range_bounds = no <effects> }` |

"From scope: none" means the iterator is global and can be used from any scope.
"""
    text = header(f"Iterators ({len(normal)} base names + generated region iterators)", "effects.log + triggers.log", intro)
    by_scope = collections.defaultdict(list)
    for row in normal:
        by_scope[row[1]].append(row)
    order = sorted(by_scope, key=lambda s: (s != "none", s))
    for scope in order:
        text += f"## From scope: {scope}\n\n| Base name | Iterates over | Description |\n|---|---|---|\n"
        for base, _s, target, desc, extra, _forms in sorted(by_scope[scope]):
            d = desc + (f" — `{extra}`" if extra else "")
            text += f"| `{base}` | {target} | {d.replace('|', '/')} |\n"
        text += "\n"

    text += "## Generated geographic-region iterators\n\n"
    text += (
        "For every geographic region defined in `common/geographic_regions`, the game generates global iterators\n"
        "over five object types. For a region whose short key is `<region>` these are:\n\n"
        "`<any|every|random|ordered>_country_in_<region>`, `..._state_in_<region>`, `..._state_region_in_<region>`,\n"
        "`..._strategic_region_in_<region>`, `..._province_in_<region>`\n\n"
        "(The description text the game prints for these is garbage — a doc-generator bug — so it is omitted here.)\n"
        "A mod that adds a geographic region gets these iterators for it automatically.\n\n"
        f"Regions present in this game version ({len(regions)}):\n\n"
    )
    text += ", ".join(f"`{r}`" for r in sorted(regions)) + "\n"
    write("iterators.md", text)

    # ---- index by scope --------------------------------------------------
    eff_by = collections.defaultdict(list)
    trg_by = collections.defaultdict(list)
    for e in plain_eff:
        for s in (e["scopes"] or "none").split(","):
            eff_by[s.strip()].append(e["name"])
    for e in plain_trg:
        for s in (e["scopes"] or "none").split(","):
            trg_by[s.strip()].append(e["name"])
    intro = """
"What can I do / check while in scope X?" — names only; look the details up in `effects.md` / `triggers.md`.
Entries under **none** work in every scope. Iterators are listed separately in `iterators.md`.
"""
    text = header("Effects and triggers indexed by scope", "effects.log + triggers.log", intro)
    scopes = sorted(set(eff_by) | set(trg_by), key=lambda s: (s != "none", s))
    for s in scopes:
        text += f"## {s}\n\n"
        if eff_by.get(s):
            text += f"**Effects ({len(eff_by[s])}):** " + ", ".join(f"`{n}`" for n in sorted(eff_by[s])) + "\n\n"
        if trg_by.get(s):
            text += f"**Triggers ({len(trg_by[s])}):** " + ", ".join(f"`{n}`" for n in sorted(trg_by[s])) + "\n\n"
    write("index_by_scope.md", text)

    # ---- database folders ------------------------------------------------
    folders = collections.defaultdict(set)
    for e in effects + triggers:
        if e["vtype"] and not is_iterator(e["name"]):
            folders[e["vtype"].rstrip("/")].add(e["name"])
    intro = """
Game database folders that the script docs name as the source of keys for at least one effect or trigger.
This is a *verified-to-exist* list for this game version, not a complete list of `common/` subfolders.
"""
    text = header("Database folders referenced by effects/triggers", "effects.log + triggers.log", intro)
    text += "| Folder (under `game/`) | Used by (examples) |\n|---|---|\n"
    for f in sorted(folders):
        names = sorted(folders[f])
        text += f"| `{f}` | {', '.join('`' + n + '`' for n in names[:6])}{' …' if len(names) > 6 else ''} |\n"
    write("database_folders.md", text)

    return len(plain_eff), len(plain_trg), len(normal), len(regions)


def build_event_targets():
    text_in = read("event_targets.log")
    main, _sep, code = text_in.partition("Event Targets Saved from Code:")
    main = re.sub(r"\n-{10,}\s*$", "\n", main.rstrip() + "\n")
    entries = []
    for block in re.split(r"^### ", main, flags=re.M)[1:]:
        lines = [l.rstrip() for l in block.split("\n")]
        d = dict(name=lines[0].strip(), desc=[], inp="", out="", data=False, glob=False, wild=False)
        for l in lines[1:]:
            if l.startswith("Input Scopes:"):
                d["inp"] = l.split(":", 1)[1].strip()
            elif l.startswith("Output Scopes:"):
                d["out"] = l.split(":", 1)[1].strip()
            elif l.startswith("Requires Data:"):
                d["data"] = True
            elif l.startswith("Global Link:"):
                d["glob"] = True
            elif l.startswith("Wild Card:"):
                d["wild"] = True
            elif l.strip() and not re.match(r"^-{5,}$", l.strip()):
                d["desc"].append(l.strip())
        entries.append(d)
    saved = [l.strip() for l in code.split("\n") if l.strip()]

    intro = """
Event targets ("links") move from one scope to another, or read a value from the current scope.

* **Takes a key** (`Requires Data: yes` in the game's docs) means the link is written `name:key`, e.g. `c:FRA`,
  `ig:ig_landowners`, `relations:root`, `modifier:country_prestige_add`. Links that take a *scope* as their
  argument can also be written in function form inside quotes: `"military_reach(scope:target_state)"`.
* Links without a key are chained with dots: `root.capital.state_region`, `scope:target.owner.ruler`.
* A link whose output is `value` can be used anywhere a number is expected (script values, comparisons).
* Inside the tables a literal pipe is written `\\|` (markdown escaping): `define:Namespace\\|Name` means
  `define:Namespace|Name` in script.
"""
    text = header(f"Event targets ({len(entries)})", "event_targets.log", intro)

    def row(d):
        key = "yes" if d["data"] else ""
        desc = " / ".join(d["desc"]).replace("|", "\\|")
        return f"| `{d['name']}` | {d['inp'] or '-'} | {d['out'] or 'any'} | {key} | {desc} |\n"

    glob = [d for d in entries if not d["inp"]]
    scoped = [d for d in entries if d["inp"]]
    text += "## Global links and literals (usable from any scope)\n\n| Name | Input | Output | Takes a key | Description |\n|---|---|---|---|---|\n"
    for d in sorted(glob, key=lambda d: d["name"]):
        text += row(d)
    text += "\n## Scope links to other objects\n\n| Name | Input scopes | Output | Takes a key | Description |\n|---|---|---|---|---|\n"
    for d in sorted((d for d in scoped if d["out"] not in ("value", "value, boolean")), key=lambda d: d["name"]):
        text += row(d)
    text += "\n## Value links (read a number/boolean from the scope)\n\n| Name | Input scopes | Output | Takes a key | Description |\n|---|---|---|---|---|\n"
    for d in sorted((d for d in scoped if d["out"] in ("value", "value, boolean")), key=lambda d: (d["inp"], d["name"])):
        text += row(d)
    text += "\n## Scope names saved by game code\n\n"
    text += (
        "The game's C++ code saves scopes under these names before running certain script (on-actions, AI\n"
        "evaluations, treaty/diplomatic script, journal entries, etc.). They are read as `scope:<name>`. Which ones\n"
        "exist depends entirely on the context — check a vanilla file of the same type to see what is available.\n\n"
    )
    text += ", ".join(f"`{s}`" for s in saved) + "\n"
    write("event_targets.md", text)
    return len(entries), len(saved)


def build_modifiers():
    text_in = read("modifiers.log")
    parts = re.split(r"^--- (.*?) ---$", text_in, flags=re.M)
    sections = {}
    for i in range(1, len(parts), 2):
        ents, cur = [], None
        for l in parts[i + 1].split("\n"):
            m = re.match(r"^(\S+):$", l)
            if m:
                cur = dict(name=m.group(1), mask="", disp="", desc="")
                ents.append(cur)
                continue
            if cur is None:
                continue
            for key, field in (("Mask", "mask"), ("Name", "disp"), ("Description", "desc")):
                m = re.match(rf"^  {key}: (.*)$", l)
                if m:
                    cur[field] = m.group(1).strip()
        sections[parts[i]] = ents

    static = sections.get("Static modifier types", [])
    dynamic = sections.get("Dynamic modifier types", [])
    potential = sections.get("Potential dynamic modifier types", [])

    def cell(s):
        return s.replace("|", "/")

    intro = """
Modifier **types** hard-coded in the game. The *Mask* is the kind of object the modifier is evaluated on
(see chapter 07 for which masks apply where). Suffix conventions: `_add` flat amount, `_mult` percentage
(0.1 = +10%), `_bool` flag (`= yes`), `_factor` multiplier applied to another value.

Display names contain `icon!` fragments because the game strips its text icons when printing the docs.
"""
    text = header(f"Modifier types — static ({len(static)})", "modifiers.log", intro)
    by_mask = collections.defaultdict(list)
    for e in static:
        by_mask[e["mask"] or "(none)"].append(e)
    for mask in sorted(by_mask):
        text += f"## Mask: {mask} ({len(by_mask[mask])})\n\n| Modifier type | In-game name | Description |\n|---|---|---|\n"
        for e in by_mask[mask]:
            text += f"| `{e['name']}` | {cell(e['disp'])} | {cell(e['desc'])} |\n"
        text += "\n"
    write("modifier_types_static.md", text)

    intro = """
Modifier types the game **generates from database entries** (one per goods, pop type, building type, building
group, culture, law, institution, ...) and that are *currently referenced* by loaded game data. If you add a new
goods / building / pop type / etc. in a mod, the matching types are generated for it as well.
Naming patterns are explained in chapter 07. One line per type: `name — in-game name`.
"""
    text = header(f"Modifier types — dynamic, in use ({len(dynamic)})", "modifiers.log", intro)
    by_mask = collections.defaultdict(list)
    for e in dynamic:
        by_mask[e["mask"] or "(none)"].append(e)
    for mask in sorted(by_mask):
        text += f"## Mask: {mask} ({len(by_mask[mask])})\n\n```\n"
        for e in by_mask[mask]:
            text += e["name"] + (f" — {e['disp']}" if e["disp"] else "") + "\n"
        text += "```\n\n"
    write("modifier_types_dynamic.md", text)

    lines = [
        "# Modifier types - potential dynamic (valid, but not referenced by any loaded game data)",
        "# Generated by tools/build_reference.py from modifiers.log. Format: name<TAB>mask",
        "# These are legal to use; the game simply has not needed to instantiate them yet.",
    ]
    lines += [f"{e['name']}\t{e['mask']}" for e in potential]
    write("modifier_types_potential.txt", "\n".join(lines) + "\n")
    return len(static), len(dynamic), len(potential)


def build_on_actions():
    text_in = read("on_actions.log")
    ents = re.findall(r"^(\S+):\nFrom Code: (\w+)\nExpected Scope: (\w+)", text_in, flags=re.M)
    code = sorted(e for e in ents if e[1] == "Yes")
    script = sorted(e for e in ents if e[1] == "No")
    intro = """
**From code** on-actions are fired by the game engine; a mod hooks into them by defining an on-action of the same
name (contents are merged, see chapter 09). **Script** on-actions are ordinary vanilla on-actions that are only
fired because another on-action or effect calls them.

The *Expected scope* column is what the game reports. For most code on-actions it reports `none`, which only means
the engine does not declare a type — the root scope still exists. Read the vanilla
`common/on_actions/00_code_on_actions.txt` comments for the real root and saved scopes of each one.
"""
    text = header(f"On-actions ({len(ents)})", "on_actions.log", intro)
    text += f"## Fired from code ({len(code)})\n\n| On-action | Expected scope |\n|---|---|\n"
    for n, _c, s in code:
        text += f"| `{n}` | {s} |\n"
    text += f"\n## Defined in script only ({len(script)})\n\n| On-action | Expected scope |\n|---|---|\n"
    for n, _c, s in script:
        text += f"| `{n}` | {s} |\n"
    write("on_actions.md", text)
    return len(code), len(script)


def build_custom_loc():
    text_in = read("custom_localization.log")
    ents = []
    for block in re.split(r"^-{10,}$", text_in, flags=re.M):
        m = re.search(
            r"^(\S+):\n\nScope: (\S+)\nRandom Valid: (\w+)\n(?:Parent: (\S+)\n)?(?:Suffix: (\S+)\n)?\nEntries:\n(.*)",
            block.strip() + "\n",
            flags=re.S | re.M,
        )
        if m:
            entries = [l.strip() for l in m.group(6).split("\n") if l.strip()]
            ents.append((m.group(1), m.group(2), m.group(3), entries, m.group(4), m.group(5)))
    intro = """
Custom localization keys defined in `common/customizable_localization`. Use one in loc text as
`[SCOPE.GetCustom('key')]` where SCOPE is a data-function scope of the listed type (e.g.
`[ROOT.GetCountry.GetCustom('key')]` or `[SCOPE.sCountry('name').GetCustom('key')]`).
"Random valid" means one of the valid entries is picked at random instead of the first valid one.
Keys marked "inherits" are declared with a parent key and a suffix: they reuse the parent's entries and
triggers, appending the suffix to each entry's localization key.
"""
    text = header(f"Custom localization ({len(ents)})", "custom_localization.log", intro)
    by_scope = collections.defaultdict(list)
    for e in ents:
        by_scope[e[1]].append(e)
    for scope in sorted(by_scope):
        text += f"## Scope: {scope} ({len(by_scope[scope])})\n\n"
        for name, _s, rnd, entries, parent, suffix in sorted(by_scope[scope], key=lambda e: e[0]):
            flags = " *(random valid)*" if rnd == "yes" else ""
            if parent:
                text += f"- `{name}`{flags} — inherits the entries of `{parent}` with suffix `{suffix}`\n"
                continue
            shown = ", ".join(entries[:8]) + (f", … (+{len(entries) - 8} more)" if len(entries) > 8 else "")
            text += f"- `{name}`{flags} — {len(entries)} entries: {shown}\n"
        text += "\n"
    write("custom_localization.md", text)
    return len(ents)


def main():
    if not DOCS.is_dir():
        sys.exit(f"Docs folder not found: {DOCS}\nRun `script_docs` in the game console first, or pass the folder as argument 1.")
    OUT.mkdir(parents=True, exist_ok=True)
    print(f"docs: {DOCS}\nout:  {OUT}\n")
    n_eff, n_trg, n_iter, n_reg = build_effects_triggers()
    n_et, n_saved = build_event_targets()
    n_static, n_dyn, n_pot = build_modifiers()
    n_code, n_script = build_on_actions()
    n_loc = build_custom_loc()
    print(
        f"\n{n_eff} effects, {n_trg} triggers, {n_iter} iterator bases (+{n_reg} regions x 5 object types), "
        f"{n_et} event targets (+{n_saved} code-saved scope names), "
        f"{n_static}/{n_dyn}/{n_pot} static/dynamic/potential modifier types, "
        f"{n_code} code + {n_script} script on-actions, {n_loc} custom loc keys"
    )


if __name__ == "__main__":
    main()
