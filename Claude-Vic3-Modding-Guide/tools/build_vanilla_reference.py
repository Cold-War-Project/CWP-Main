#!/usr/bin/env python3
"""Build reference/vanilla/ from the installed game's files (keys, scripted effects/triggers, on-action scopes...).

Usage:
    python build_vanilla_reference.py [GAME_DIR] [OUT_DIR]

GAME_DIR defaults to  F:/SteamLibrary/steamapps/common/Victoria 3/game
OUT_DIR  defaults to  ../reference/vanilla (next to this script)

Re-run after every game patch. Standard library only. Reads the game folder, never writes to it.
"""
import collections
import datetime
import json
import re
import sys
from pathlib import Path

GAME = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("F:/SteamLibrary/steamapps/common/Victoria 3/game")
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "reference" / "vanilla"


def read(path):
    return path.read_bytes().decode("utf-8-sig", errors="replace").replace("\r\n", "\n")


def write(name, text):
    (OUT / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {name:34} {len(text):>9,} chars")


def game_version():
    settings = GAME.parent / "launcher" / "launcher-settings.json"
    try:
        return json.loads(read(settings)).get("version", "unknown")
    except Exception:
        return "unknown"


VERSION = game_version()


def header(title, intro=""):
    stamp = datetime.date.today().isoformat()
    out = f"# {title}\n\n> Generated by `tools/build_vanilla_reference.py` on {stamp} from the game files, "
    out += f"game version **{VERSION}**. Do not edit by hand; re-run the tool instead.\n\n"
    if intro:
        out += intro.strip() + "\n\n"
    return out


def strip_comment(line):
    out, in_string = [], False
    for ch in line:
        if ch == '"':
            in_string = not in_string
        elif ch == "#" and not in_string:
            break
        out.append(ch)
    return "".join(out)


def top_level_objects(path):
    """Yield (key, body_lines, leading_comment_lines) for each `key = {` at depth 0 of a script file."""
    lines = read(path).split("\n")
    depth = 0
    comments = []
    current = None
    for raw in lines:
        code = strip_comment(raw)
        if depth == 0:
            m = re.match(r"^\s*([A-Za-z0-9_.:\-]+)\s*\??=\s*\{", code)
            if m:
                current = (m.group(1), [], comments)
                comments = []
            elif raw.strip().startswith("#"):
                comments.append(raw.strip().lstrip("#").strip())
            else:
                comments = []  # code or a blank line detaches a comment block from the next object
        if current is not None:
            current[1].append(raw)
        depth += code.count("{") - code.count("}")
        if depth <= 0:
            depth = 0
            if current is not None:
                yield current
                current = None


def files(sub, pattern="*.txt"):
    folder = GAME / sub
    return sorted(folder.rglob(pattern)) if folder.is_dir() else []


def field(body_lines, name):
    for raw in body_lines[1:]:
        m = re.match(rf"^\s*{name}\s*=\s*\"?([A-Za-z0-9_.:\-/]+)\"?", strip_comment(raw))
        if m:
            return m.group(1)
    return ""


def keys_in(sub):
    out = []
    for f in files(sub):
        for key, _body, _c in top_level_objects(f):
            out.append(key)
    return out


def grouped(sub, by):
    groups = collections.defaultdict(list)
    for f in files(sub):
        for key, body, _c in top_level_objects(f):
            groups[field(body, by) or "(none)"].append(key)
    return groups


def fmt_list(keys):
    return ", ".join(f"`{k}`" for k in keys)


