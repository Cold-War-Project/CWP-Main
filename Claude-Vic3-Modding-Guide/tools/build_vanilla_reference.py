def build_scripted():
    def collect(sub):
        rows = []
        for f in files(sub):
            for key, body, comments in top_level_objects(f):
                params = sorted(set(re.findall(r"\$([A-Za-z0-9_]+)\$", "\n".join(body))))
                comment = " ".join(c for c in comments[-3:] if c and not set(c) <= set("#=-*_ "))
                rows.append((key, params, f.relative_to(GAME).as_posix(), comment[:160]))
        return sorted(rows)

    for kind, sub, call in (
        ("effects", "common/scripted_effects", "`name = yes` or `name = { PARAM = value }`"),
        ("triggers", "common/scripted_triggers", "`name = yes` / `name = no` or `name = { PARAM = value }`"),
    ):
        rows = collect(sub)
        intro = f"""
Scripted {kind} defined by vanilla in `{sub}`. They are called like built-in {kind} ({call}) and run in
the caller's scope. Parameters are the `$NAME$` placeholders found in the body. Read the definition in the
listed file before using one: many assume specific scopes or saved scopes. One line each:
`name(PARAMS)` — file — comment above the definition (if any).
"""
        text = header(f"Vanilla scripted {kind} ({len(rows)})", intro)
        by_file = collections.defaultdict(list)
        for key, params, path, comment in rows:
            by_file[path].append((key, params, comment))
        for path in sorted(by_file):
            text += f"## {path}\n\n"
            for key, params, comment in by_file[path]:
                sig = f"`{key}({', '.join(params)})`" if params else f"`{key}`"
                text += f"- {sig}" + (f" — {comment}" if comment else "") + "\n"
            text += "\n"
        write(f"scripted_{kind}.md", text)

    # script values
    rows = []
    for f in files("common/script_values"):
        content = read(f)
        depth = 0
        for raw in content.split("\n"):
            code = strip_comment(raw)
            if depth == 0:
                m = re.match(r"^\s*([A-Za-z0-9_.\-]+)\s*=\s*(\{|[-0-9.]+)", code)
                if m:
                    rows.append((m.group(1), "" if m.group(2) == "{" else m.group(2), f.relative_to(GAME).as_posix()))
            depth = max(0, depth + code.count("{") - code.count("}"))
    intro = """
Named script values defined by vanilla in `common/script_values`. Usable wherever a number is expected.
Constants show their value; formulas show `{…}` (read the file for the definition and the scope it expects).
"""
    text = header(f"Vanilla script values ({len(rows)})", intro)
    by_file = collections.defaultdict(list)
    for name, val, path in rows:
        by_file[path].append(f"`{name}` = {val}" if val else f"`{name}` = {{…}}")
    for path in sorted(by_file):
        text += f"## {path}\n\n" + ", ".join(by_file[path]) + "\n\n"
    write("script_values.md", text)

    # scripted lists
    rows = []
    for f in files("common/scripted_lists"):
        for key, body, _c in top_level_objects(f):
            rows.append((key, field(body, "base")))
    intro = """
Scripted lists (`common/scripted_lists`) define new iterators from an existing one plus a filter:

```
my_list = {
	base = country            # an existing iterator base name
	conditions = { <triggers> }
}
```

Each generates `any_<name>`, `every_<name>`, `random_<name>` and `ordered_<name>`, usable in the same scopes as
the base iterator. These do not appear in the game's `script_docs` output.
"""
    text = header(f"Vanilla scripted lists ({len(rows)})", intro)
    text += "| List name | Base iterator |\n|---|---|\n"
    for key, base in sorted(rows):
        text += f"| `{key}` | `{base}` |\n"
    write("scripted_lists.md", text)


def build_on_action_scopes():
    intro = """
The comment above each engine on-action in vanilla's `common/on_actions/00_code_on_actions.txt`, which is where
Paradox documents the **root scope and saved scopes** of each one. (The `script_docs` output reports
"Expected Scope: none" for most of these.) An on-action with no comment is listed with a dash; for the
pulses, the roots are documented in `common/on_actions/_on_actions.md` and in chapter 09 of the guide.
"""
    path = GAME / "common/on_actions/00_code_on_actions.txt"
    if not path.is_file():
        return
    lines = read(path).split("\n")
    rows = []
    depth = 0
    comments = []
    for raw in lines:
        code = strip_comment(raw)
        if depth == 0:
            m = re.match(r"^([A-Za-z0-9_]+)\s*=\s*\{", code)
            if m:
                rows.append((m.group(1), [c for c in comments if c]))
                comments = []
            elif raw.strip().startswith("#"):
                comments.append(raw.strip().lstrip("#").strip())
            else:
                comments = []
        depth = max(0, depth + code.count("{") - code.count("}"))
    text = header(f"Engine on-actions: root and saved scopes ({len(rows)})", intro)
    for name, comments in rows:
        text += f"## {name}\n\n"
        text += ("\n".join(f"- {c}" for c in comments) if comments else "- —") + "\n\n"
    write("on_action_scopes.md", text)


def build_assets():
    intro = """
Asset names and paths that vanilla script refers to, with how often each is used. Copy from here instead of
inventing a path: a missing texture, video or sound shows a placeholder and logs an error.
"""
    text = header("Vanilla asset names used in script", intro)

    def count(sub, regex, glob="*.txt"):
        c = collections.Counter()
        for f in files(sub, glob):
            for m in re.finditer(regex, read(f)):
                c[m.group(1)] += 1
        return c

    def section(title, counter, note=""):
        nonlocal text
        text += f"## {title} ({len(counter)})\n\n"
        if note:
            text += note + "\n\n"
        text += ", ".join(f"`{k}` ({v})" for k, v in sorted(counter.items(), key=lambda kv: (-kv[1], kv[0]))) + "\n\n"

    section("Event videos — `event_image = { video = \"…\" }`", count("events", r'video\s*=\s*"?([A-Za-z0-9_/.]+)"?'))
    section("Event icons — `icon = \"…\"`", count("events", r'icon\s*=\s*"?(gfx/[A-Za-z0-9_/.]+)"?'))
    section("Event window types — `gui_window = …`", count("events", r"gui_window\s*=\s*([A-Za-z0-9_]+)"),
            "Events without `gui_window` use the default window.")
    section("Event sounds — `on_opened_soundeffect`", count("events", r'on_opened_soundeffect\s*=\s*"([^"]+)"'))
    section("Event sounds — `on_created_soundeffect`", count("events", r'on_created_soundeffect\s*=\s*"([^"]+)"'))
    section("Static modifier icons", count("common/static_modifiers", r'icon\s*=\s*"?(gfx/[A-Za-z0-9_/.]+)"?'))
    section("Journal entry icons", count("common/journal_entries", r'icon\s*=\s*"?(gfx/[A-Za-z0-9_/.]+)"?'))
    section("Text icons in English localization — `@name!`",
            count("localization/english", r"@([a-z_0-9]+)!", "*.yml"))
    section("Text styles in English localization — `#style text#!`",
            count("localization/english", r"#([A-Za-z_]+)[ ;:]", "*.yml"),
            "Includes a few false positives from literal `#` in text; the frequent ones are real styles.")
    write("assets.md", text)


def build_shipped_docs():
    intro = """
Paradox ships format documentation inside the game folder as `.md` files (and as comment blocks at the top
of some `.txt` files). **These are the authoritative description of each file format; read the relevant one
before creating an object of that type.** Paths are relative to the `game/` folder.
"""
    docs = [p for p in sorted(GAME.rglob("*.md")) if "gfx" not in p.relative_to(GAME).parts[:1]]
    text = header(f"Format documentation shipped with the game ({len(docs)} files)", intro)
    text += "| File | Size | First line |\n|---|---|---|\n"
    for p in docs:
        content = read(p)
        first = next((l.strip() for l in content.split("\n") if l.strip()), "")
        text += f"| `{p.relative_to(GAME).as_posix()}` | {len(content):,} | {first[:90].replace('|', '/')} |\n"
    text += "\n## Script files that start with a documentation comment block\n\n"
    rows = []
    for sub in ("common", "events"):
        for f in files(sub):
            head = read(f).split("\n")[:25]
            n = sum(1 for l in head if l.strip().startswith("#"))
            if n >= 15:
                rows.append(f.relative_to(GAME).as_posix())
    text += "\n".join(f"- `{r}`" for r in rows) + "\n"
    write("shipped_docs.md", text)


def main():
    if not (GAME / "common").is_dir():
        sys.exit(f"Not a Victoria 3 game folder (no common/): {GAME}")
    OUT.mkdir(parents=True, exist_ok=True)
    print(f"game: {GAME}  (version {VERSION})\nout:  {OUT}\n")
    build_database_keys()
    build_scripted()
    build_on_action_scopes()
    build_assets()
    build_shipped_docs()


if __name__ == "__main__":
    main()
