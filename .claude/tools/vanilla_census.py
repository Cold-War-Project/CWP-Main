# --------------------------------------------------------------------------- parser

TOKEN_RE = re.compile(r'''
    (?P<comment>\#[^\n]*)
  | (?P<string>"(?:[^"\\]|\\.)*")
  | (?P<op>\?=|>=|<=|!=|==|=|>|<)
  | (?P<open>\{)
  | (?P<close>\})
  | (?P<atom>[^\s{}=<>!?"\#]+(?:\?(?!=))?)
''', re.X)


def read(path):
    with open(path, 'rb') as f:
        data = f.read()
    if data.startswith(b'\xef\xbb\xbf'):
        data = data[3:]
    return data.decode('utf-8', errors='replace')


def parse(text):
    """Returns a list of (key, op, value); bare values have key None. value is str or list."""
    toks = [(m.lastgroup, m.group(m.lastgroup)) for m in TOKEN_RE.finditer(text) if m.lastgroup != 'comment']
    pos = 0

    def block():
        nonlocal pos
        items = []
        while pos < len(toks):
            k, v = toks[pos]
            if k == 'close':
                pos += 1
                return items
            if k == 'open':
                pos += 1
                items.append((None, None, block()))
                continue
            if k == 'op':
                pos += 1
                continue
            pos += 1
            if pos < len(toks) and toks[pos][0] == 'op':
                op = toks[pos][1]
                pos += 1
                if pos >= len(toks):
                    items.append((v, op, ''))
                    break
                k2, v2 = toks[pos]
                if k2 == 'open':
                    pos += 1
                    items.append((v, op, block()))
                elif k2 == 'close':
                    items.append((v, op, ''))
                else:
                    pos += 1
                    if pos < len(toks) and toks[pos][0] == 'open' and v2 in ('rgb', 'hsv', 'hsv360'):
                        pos += 1
                        items.append((v, op, block()))
                    else:
                        items.append((v, op, v2))
            else:
                items.append((None, None, v))
        return items

    return block()


def walk_files(root, ext='.txt'):
    for dp, _dn, fn in os.walk(root):
        for f in sorted(fn):
            if f.lower().endswith(ext):
                yield os.path.join(dp, f)


def fmt(counter, top=None, minimum=1):
    items = [(k, n) for k, n in counter.most_common(top) if n >= minimum]
    return ', '.join(f"`{k}` {n}" for k, n in items)


# --------------------------------------------------------------------------- field census

FREEFORM = {'script_values', 'scripted_effects', 'scripted_triggers', 'static_modifiers', 'named_colors',
            'scripted_rules', 'defines', 'dna_data', 'genes', 'ethnicities', 'coat_of_arms', 'technology',
            'history', 'tutorial_lessons', 'game_rules', 'culture_graphics', 'alert_groups', 'travel_network'}


def census_folder(game, rel, depth=1, top=60):
    root = os.path.join(game, rel)
    if not os.path.isdir(root):
        return None
    files = [os.path.join(root, f) for f in sorted(os.listdir(root)) if f.lower().endswith('.txt')]
    c = collections.Counter()
    entries = 0
    for f in files:
        level = [parse(read(f))]
        for _ in range(depth - 1):
            level = [v for t in level for _k, _o, v in t if isinstance(v, list)]
        for t in level:
            for k, _op, v in t:
                if k is None or not isinstance(v, list):
                    continue
                entries += 1
                c.update({k2 + (' {}' if isinstance(v2, list) else '') for k2, _o2, v2 in v if k2 is not None})
    line = fmt(c, top)
    extra = f" *(+{len(c) - top} rarer keys)*" if len(c) > top else ''
    return f"### `{rel}` - {len(files)} files, {entries} entries\n{line}{extra}\n"


def write_fields(game, out):
    parts = ["# Vanilla field census (generated)\n",
             "Generated by `.claude/tools/vanilla_census.py` from the installed base game. For every database folder: "
             "the keys that appear directly inside an entry, with the number of entries using them. `{}` marks a "
             "block-valued key. A key listed here is proven to parse in this game version; a key **not** listed is "
             "unused by vanilla, so check the folder's `.md`/header comments or treat it as suspect. Counts show how "
             "common a key is, not whether it is required.\n"]
    common = os.path.join(game, 'common')
    for d in sorted(os.listdir(common)):
        if os.path.isdir(os.path.join(common, d)) and d not in FREEFORM:
            s = census_folder(game, 'common/' + d)
            if s:
                parts.append(s)
    parts.append(census_folder(game, 'common/technology/technologies'))
    parts.append(census_folder(game, 'common/technology/eras'))
    parts.append(census_folder(game, 'common/coat_of_arms/coat_of_arms', top=12))
    parts.append("\n## History files (keys inside the third level, i.e. inside `c:TAG = { ... }` / "
                 "`s:STATE = { region_state:TAG = { ... } }`)\n")
    hist = os.path.join(common, 'history')
    for d in sorted(os.listdir(hist)):
        s = census_folder(game, 'common/history/' + d, depth=3, top=35)
        if s:
            parts.append(s)
    with open(os.path.join(out, 'vanilla-fields.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(p for p in parts if p))


# --------------------------------------------------------------------------- token census

TRIG_BLOCKS = {'trigger', 'limit', 'possible', 'potential', 'is_shown', 'can_enact', 'is_visible', 'visible',
               'enable', 'ai_will_do', 'can_impose', 'cancellation_trigger', 'creation_trigger', 'is_valid',
               'happened', 'attainable', 'can_establish_in', 'country_trigger', 'state_trigger', 'complete',
               'invalid', 'is_shown_when_inactive', 'should_be_involved', 'can_build', 'can_repeal', 'selectable',
               'pop_potential', 'conditions', 'valid', 'disband_trigger', 'has_access', 'pop_criteria',
               'can_create', 'show_as_unavailable', 'can_ratify'}
EFF_BLOCKS = {'immediate', 'effect', 'option', 'after', 'on_activate', 'on_deactivate', 'when_taken', 'on_enable',
              'on_disable', 'on_created', 'on_enact', 'on_researched', 'on_start', 'hidden_effect', 'on_enforced',
              'on_war_begins', 'on_war_end', 'accept_effect', 'decline_effect', 'on_entry_into_force',
              'on_withdrawal', 'on_break', 'on_government_type_change', 'on_post_government_type_change',
              'on_complete', 'on_create', 'on_invalid', 'on_career_end', 'on_disbanded', 'trait_generation',
              'on_character_ig_membership'}
LOGIC = {'AND', 'OR', 'NOT', 'NOR', 'NAND', 'trigger_if', 'trigger_else_if', 'trigger_else', 'if', 'else_if',
         'else', 'limit', 'custom_tooltip', 'hidden_trigger', 'hidden_effect', 'show_as_tooltip', 'random',
         'random_list', 'while', 'switch'}
PFXKEY = re.compile(r'^[a-z_]+:')
PFX = re.compile(r'(?<![A-Za-z0-9_.])([a-z_]+):[A-Za-z0-9_$]')
ITER = re.compile(r'\b((?:every|any|random|ordered)_[a-z_]+)\s*=\s*\{')


def clean(k):
    if k.startswith('"') or '$' in k or '.' in k or PFXKEY.match(k) or k[0].isdigit() or k[0] == '@' or k.isupper():
        return None
    return k


def write_tokens(game, out):
    trig, eff = collections.Counter(), collections.Counter()
    prefix, iters = collections.Counter(), collections.Counter()

    def walk(items, ctx):
        for k, _op, v in items:
            if k is None:
                if isinstance(v, list):
                    walk(v, ctx)
                continue
            nctx = ctx
            if k == 'limit':
                nctx = 'T'
            elif k in EFF_BLOCKS and ctx != 'T':
                nctx = 'E'
            elif k in TRIG_BLOCKS:
                nctx = 'T'
            elif ctx:
                ck = clean(k)
                if ck and ck not in LOGIC:
                    (trig if ctx == 'T' else eff)[ck] += 1
            if isinstance(v, list):
                walk(v, nctx)

    ev_keys, opt_keys, ev_types, n_events = collections.Counter(), collections.Counter(), collections.Counter(), 0
    for sub in ('common', 'events'):
        for f in walk_files(os.path.join(game, sub)):
            text = read(f)
            stripped = re.sub(r'"[^"\n]*"', '""', re.sub(r'#[^\n]*', '', text))
            prefix.update(PFX.findall(stripped))
            iters.update(ITER.findall(stripped))
            tree = parse(text)
            if 'history' not in f.replace('\\', '/').split('/'):
                walk(tree, None)
            if sub == 'events':
                for k, _op, v in tree:
                    if k is None or not isinstance(v, list):
                        continue
                    n_events += 1
                    ev_keys.update({k2 + (' {}' if isinstance(v2, list) else '') for k2, _o, v2 in v if k2})
                    for k2, _o, v2 in v:
                        if k2 == 'type':
                            ev_types[v2] += 1
                        if k2 == 'option' and isinstance(v2, list):
                            opt_keys.update({k3 for k3, _o3, _v3 in v2 if k3})

    # iterator bases: drop trigger-localization artefacts and per-geographic-region generated lists
    suffixes = ('_all', '_count', '_percent')
    bases = collections.Counter()
    for name, n in iters.items():
        if '_in_' in name and re.search(r'_(country|state|state_region|strategic_region|province)_in_(?!geographic_region|list|global_list|local_list|hierarchy|exile_pool|jail|void|siberia|government|opposition|front|theater|state_region|strategic_region|state$|country$)', name):
            continue
        if name.endswith(suffixes) and n <= 2:
            continue
        kind, _, base = name.partition('_')
        if base in ('list', 'events', 'range', 'valid', 'false', 'kindness', 'on_actions'):
            continue  # random_list / random_events / random_range etc. are not list iterators
        bases[base] += n
    P = ["# Vanilla script token census (generated)\n",
         "Generated by `.claude/tools/vanilla_census.py`. Everything here is harvested from what vanilla actually "
         "uses, so each name is known to exist in this game version. It is **not** a complete engine list: the "
         "authoritative lists come from the `script_docs` console command (see `debugging.md`). The trigger/effect "
         "lists are heuristic (classified by the block they appear in) and also contain parameter names and scope "
         "links; use them to confirm a name exists, then grep vanilla for a usage example.\n",
         "## Scope/database prefixes (`prefix:key`) by usage\n", fmt(prefix, 80, 2), "\n",
         "## List iterators\nEvery base below exists as `any_<base>` (trigger), `every_<base>`, `random_<base>`, "
         "`ordered_<base>` (effects). Geographic regions add `<kind>_country_in_<short_key>`, "
         "`<kind>_state_in_<short_key>`, `<kind>_state_region_in_<short_key>` automatically from "
         "`common/geographic_regions` `short_key`; scripted lists add theirs from `common/scripted_lists`. A few count-1 names are scripted "
         "triggers whose own name starts with `any_`, not iterators.\n",
         ', '.join(f"`{k}` {n}" for k, n in sorted(bases.items())), "\n",
         f"## Events ({n_events} in vanilla)\n",
         "Types: " + fmt(ev_types), "\n", "Event keys: " + fmt(ev_keys, 60), "\n",
         "Option keys (non-effect ones are `name`, `default_option`, `highlighted_option`, `ai_chance`, `trigger`, "
         "`show_as_unavailable`): " + fmt(opt_keys, 30), "\n",
         "## Names seen in trigger context (count >= 10)\n", fmt(trig, None, 10), "\n",
         "## Names seen in effect context (count >= 8)\n", fmt(eff, None, 8), "\n"]
    with open(os.path.join(out, 'vanilla-script-tokens.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(P))


# --------------------------------------------------------------------------- on_actions

def write_on_actions(game, out):
    path = os.path.join(game, 'common/on_actions/00_code_on_actions.txt')
    lines = read(path).replace('\r', '').split('\n')
    P = ["# Code-fired on_actions (generated)\n",
         "Generated by `.claude/tools/vanilla_census.py` from `common/on_actions/00_code_on_actions.txt`: every "
         "on_action the engine fires, with the scope comments Paradox wrote above it. An on_action name not in "
         "this list is only fired if script fires it.\n"]
    comments = []
    for ln in lines:
        s = ln.strip()
        if s.startswith('#'):
            comments.append(s.lstrip('# ').strip())
            continue
        m = re.match(r'^([a-z_0-9]+)\s*=\s*\{', ln)
        if m:
            note = ' '.join(c for c in comments if c)
            P.append(f"- `{m.group(1)}`" + (f" - {note}" if note else ''))
        if s:
            comments = []
    with open(os.path.join(out, 'vanilla-on-actions.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(P) + '\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--game', default=DEFAULT_GAME)
    ap.add_argument('--out', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'reference'))
    a = ap.parse_args()
    if not os.path.isdir(os.path.join(a.game, 'common')):
        sys.exit(f"No common/ folder under {a.game}")
    os.makedirs(a.out, exist_ok=True)
    write_fields(a.game, a.out)
    write_on_actions(a.game, a.out)
    write_tokens(a.game, a.out)
    print("wrote", os.path.abspath(a.out))


if __name__ == '__main__':
    main()
