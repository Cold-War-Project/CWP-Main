"""Regenerates the .claude/reference/vanilla-*.md files from the installed base game.

Run after every game patch:
    python ".claude/tools/vanilla_census.py"
    python ".claude/tools/vanilla_census.py" --game "D:/other/Victoria 3/game"

Reads only; writes only into .claude/reference/. No third-party packages.
"""
import argparse
import collections
import os
import re
import sys

